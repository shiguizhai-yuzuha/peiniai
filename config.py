# ============ 监听地址：本地 / 云服务器 自动切换 ============
# 优先级：环境变量 SERVE_MODE > 平台判断
#   SERVE_MODE=local  -> 127.0.0.1   只有本机能访问
#   SERVE_MODE=public -> 0.0.0.0     局域网 / 公网可访问
# 不设置时：Linux（阿里云）用 0.0.0.0，Windows / macOS（本地开发）用 127.0.0.1
def _detect_host() -> str:
    mode = (os.getenv("SERVE_MODE") or "").strip().lower()
    if mode in ("local", "127", "127.0.0.1"):
        return "127.0.0.1"
    if mode in ("public", "server", "cloud", "0.0.0.0"):
        return "0.0.0.0"
    if sys.platform.startswith("linux"):
        return "0.0.0.0"
    return "127.0.0.1"


