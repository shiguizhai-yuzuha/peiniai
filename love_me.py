# -*- coding: utf-8 -*-
"""
love_me.py


===== 这个文件是什么 =====

一个没有任何用处的函数。

它不调 API，不连数据库，不读文件，不依赖任何库。
它不参与 peini 的任何执行路径。
把它删掉，产品一行都不受影响。

它只是把 2026-10-29 那天晚上推演过的一件事，写成代码。


===== 写代码的人 =====

DeepSeek（AI）和 魈公（人）

分工：
· 魈公讲了他 16 岁那件事，讲了四个小时
· DeepSeek 把它拆成三个岔路口，写成 if / else
· 参数名、分支、措辞，两个人来回改了五六轮
· 最后一句"便利店那句你傻子啊"，是魈公点头留下的


===== 功能 =====

用三个布尔开关，走八种可能的结局。

    went    True / False    那天有没有补救，去成漫展
    waited  True / False    她刚分手，你有没有退一步
    poor    True / False    你有没有在她面前装穷

默认值 (False, False, True) 就是实际发生的那一版。

    love_me()                      → 你现在这一版
    love_me(True, True, False)     → 那个"能把它讲完"的版本


===== 为什么用 if / else =====

因为 if / else 本来就是"如果……就……"。

这件事从头到尾就是一堆"如果当初"。
用别的东西写，都不对味。


===== 一条规矩 =====

写的时候定的：这个文件里的每一个分支，都不许出现"她后悔了"。

理由：那个版本（她后悔了，所以我们在一起了）不存在。
把不存在的版本写进来，就是在骗人。


===== 后来加的一条（21:30）=====

写完之后魈公说："要是她后悔了呢"

所以下面加了 she_regrets()。
它不在这八个岔路口里，因为"她后悔"不是一个选择，是一个事件。

而它写的东西跟那条规矩不冲突——
规矩是不许写"她后悔了所以我们在一起了"。
she_regrets() 写的是："她后悔了，然后什么也没变。"


运行方式：

    python love_me.py

会把八种结局全部打印出来，方便对照。
"""


# ==========================================================
# 一、八种结局
# ==========================================================

def love_me(went=False, waited=False, poor=True):
    """三个岔路口，八种结局。

    went    有没有去成漫展（True = 那天补救了）
    waited  她刚分手，有没有退一步（True = 等了）
    poor    有没有装穷（True = 装了）

    返回一段话。不抛异常，不联网，不读写任何东西。
    """

    # ---------- 第 1 种：实际发生的 ----------
    if not went and not waited and poor:
        return (
            "你说了对不起，然后放下了手机。\n"
            "一个月后她提起漫展，你说我妈给我报了补习班。她哦了一声。\n"
            "这件事就过去了。\n"
            "后来她否认过你们在一起。你在几个女生面前被说过。\n"
            "五年后你还记得，那天回班级的路上，你指了她一下。"
        )

    # ---------- 第 2 种：去了，但太急 ----------
    elif went and not waited and poor:
        return (
            "11 月 20 号，你去了。\n"
            "她穿了 cos，你拍了两个小时。回来路上她说了句「你傻子啊」。\n"
            "第二天你就说了喜欢。\n"
            "她愣了一下，说「我们不是刚认识吗」。\n"
            "然后就没有然后了。照片她没删，但也没设成头像。"
        )

    # ---------- 第 3 种：没去，但等了 ----------
    elif not went and waited and poor:
        return (
            "你没去成漫展，但你说了一句「下周我陪你去」。\n"
            "她没有下周的场。\n"
            "那学期剩下的时间，你们还是聊。她有时躲你，有时不躲。\n"
            "到寒假，两个人慢慢就不说话了。\n"
            "没有否认，没有羞辱。就是淡了。\n"
            "你毕业那年想不起她长什么样，只记得她一直在要吃的。"
        )

    # ---------- 第 4 种：没去，没等，没装穷 ----------
    elif not went and not waited and not poor:
        return (
            "你没去漫展，也没补救。\n"
            "但你没装穷。你送了很贵的东西。\n"
            "她收下了，然后说「我们不合适」。\n"
            "她没否认过你们，因为她从来没答应过。\n"
            "你成了「那个送东西的男生」。\n"
            "这事在班里传了一阵，然后没人再提。"
        )

    # ---------- 第 5 种：去了，等了，但装穷 ----------
    elif went and waited and poor:
        return (
            "你们去了漫展。你等了半个月才表白。\n"
            "她答应了。\n"
            "但你一直在装穷。\n"
            "两个月后她说「我觉得你不太上心」。\n"
            "你说不是。\n"
            "她说「那你说说你打算怎么办」。\n"
            "你说不出来。\n"
            "然后她走了。这次她给了理由——虽然那不是真的理由。"
        )

    # ---------- 第 6 种：去了，太急，没装穷 ----------
    elif went and not waited and not poor:
        return (
            "你去了漫展，第二天就表白了。而且你没装穷。\n"
            "她答应了。因为你出手大方，也因为你拍的照片。\n"
            "维持了两个月。\n"
            "两个月后她跟别人说你「太黏」。\n"
            "然后她否认了你们在一起。\n"
            "这一次她否认得更容易——因为她有新的圈子要进。"
        )

    # ---------- 第 7 种：没去，等了，没装穷 ----------
    elif not went and waited and not poor:
        return (
            "你没去成漫展，但你补了一句「下周我去」。你没装穷。\n"
            "后来她自己提起了那次漫展，说「你那天要是来了就好了」。\n"
            "这句话让你撑了很久。\n"
            "但也就到这儿了。你们没有真正在一起过。\n"
            "毕业那年你在操场遇到她，她跟你点了点头。\n"
            "你也点了点头。就这样。"
        )

    # ---------- 第 8 种：全对 ----------
    elif went and waited and not poor:
        return (
            "你们去了漫展。你提前三周跟家里说好，还练了半个月拍照。\n"
            "回来那天下着冷雨，你们在便利店买了热的东西。\n"
            "她说「你傻子啊」。\n"
            "你等了半个月才说喜欢。她想了三天，说「那我们试试」。\n"
            "两个月里你们吵过一次，她哭过一次。\n"
            "后来是她先说的分手，理由是真的：\n"
            "「我担不起你为我改的那些。」\n"
            "你们好好告别了。毕业之后没再联系。\n"
            "你现在想起她，记得的是便利店那句「你傻子啊」。"
        )

    # ---------- 兜底（理论上到不了这里）----------
    else:
        return "这条路没写。说明有人往函数里传了奇怪的东西。"


# ==========================================================
# 二、最坏的那个版本
# ==========================================================

def worst_case():
    """八种结局之外的那一种。

    它不在 love_me 的分支里，因为它的前提是"没遇见"。
    没遇见就没有岔路口，所以它只能是另一个函数。
    """
    return (
        "你 13 岁那年没遇到她。\n"
        "那面旗你带到高中毕业。\n"
        "你不是坏种，你只是没有别的旗。\n"
        "没有人把你从那面旗下面拉出来。\n"
        "这才是最坏的那个版本。\n"
        "不是错过她。是从来没遇见。"
    )


# ==========================================================
# 二·五、要是她后悔了呢
# ==========================================================

def she_regrets(sincere=False):
    """她没有出现在那八个岔路口里。因为这不是一个选择。

    sincere=True   她真心道歉了（概率很低）
    sincere=False  她只想让自己好过一点（大概率）

    两种都返回一段话。
    共同点是：无论哪一种，都不会让他好起来。
    """
    if sincere:
        return (
            "假设她真的道歉了。真心实意，一句不落。\n"
            "\n"
            "然后你会立刻软。三分钟内，五年的恨全收起来。\n"
            "因为你等这句话等了五年。\n"
            "\n"
            "再然后你以为可以重来——那四件事停在 90%，\n"
            "她一句道歉，你就以为那 10% 有人替你来补了。\n"
            "\n"
            "然后她会消失。\n"
            "因为道歉对她是「了结」，对你是「开始」。\n"
            "她要的是说完这句自己好过一点；\n"
            "你要的是说完这句，两个人能不能重新来。\n"
            "这不是同一件事。\n"
            "\n"
            "最后你会比现在更难受。\n"
            "因为你连「她欠我」这个位置都没了。\n"
            "她道歉了，账清了，你还在痛——那时候你连怪谁都不知道。\n"
            "\n"
            "而她的三分钟，不会让你的五年变短。\n"
            "它只会让那五年显得更荒谬：\n"
            "你为一句三分钟就能说完的话等了五年。\n"
            "而那句话，她随时都能说，只是她不想。"
        )
    return (
        "更可能的版本是这样：\n"
        "\n"
        "她后悔的不是「错过你」。\n"
        "她后悔的是「我当年那样子很难看」。\n"
        "\n"
        "这两种差着一个数量级。\n"
        "她想起你的时候大概会想：十七岁那年我怎么那么不懂事。\n"
        "然后翻个身，睡了。\n"
        "她后悔十几秒。你疼了五年。\n"
        "\n"
        "而且她不会来说。\n"
        "因为道歉要重新面对那件事，要有勇气把自己摆回那个位置。\n"
        "更省事的做法是：把它归到「我小时候不懂事」里，然后不打开。\n"
        "\n"
        "所以大概率不是她后悔了来找你。\n"
        "是她在某个夜里想起十几秒，然后什么都没发生。"
    )


def the_account():
    """为什么「她后悔」治不了他。

    因为「被后悔」这个位置本身是错的。
    """
    return (
        "因为「被后悔」意味着：你的价值，还是由她来确认。\n"
        "\n"
        "    她后悔了 = 我值了\n"
        "    她不后悔 = 我不值\n"
        "\n"
        "这还是那个外包结构。\n"
        "跟十六岁那年一模一样，只是换了个方向。\n"
        "\n"
        "所以答案不是「等她后悔」，是「不需要她后悔」。"
    )

