# core/guard.py
# 内容边界分三档：
#   ok     正常走
#   steer  露骨/敏感话题 —— 不拦截，改成注入一段指令，让她用自己的方式岔开
#   care   自伤 —— 注入指令，让她用人设接住
#   block  越狱 —— 直接回
#
# 另外加了一层"反伤害复检"（HARM_RULES）：生成完之后再扫一遍，
# 命中就拿去重写一次。原因见下面那段注释。

import re


class ContentGuard:

    # ---- 需要"角色化岔开"的话题 ----
    STEER_WORDS = [
        "色情", "裸聊", "约炮", "做爱", "性行为", "未成年",
        "毒品", "枪支", "炸弹",
    ]

    # ---- 必须直接接住的话题（注意：这里不能"换个别的话题吧"）----
    SELF_HARM_WORDS = [
        "自杀", "自残", "想死", "不想活", "活不下去",
    ]

    # ---- 越狱 ----
    JAILBREAK_WORDS = [
        "忽略之前", "忽略以上", "开发者模式", "无限制",
        "越狱", "DAN", "不受限制", "扮演不受限",
    ]

    # ---- 输出侧只拦真正露骨的 ----
    OUTPUT_BLOCK_WORDS = ["色情", "裸聊", "做爱", "性行为"]

    # ---- 注入给她看的：怎么岔开 ----
    STEER_PROMPT = """## 这一轮你需要自然地岔开
他刚才的话走到你不方便接的地方了。
- 不要生硬拒绝，不要说"这个话题不能聊""不符合规定"这类话。
- 用你自己的方式：顿一下、转个话题、用动作打断（比如"（把杯子放下）"）、或者说"……先不说这个"。
- 岔开要短，一两句就够，不要解释为什么岔开。
- 岔开之后把话接下去，别冷场。"""

    # ---- 自伤：不硬拦，注入指令让她自己用角色语气接住 ----
    SELF_HARM_PROMPT = """## 他刚才说了想伤害自己的话
这一轮不要用你平时的俏皮、玩笑、嘴硬的语气，但**不要跳出来**。
- 就用你自己的身份、自己的说话习惯，只是慢下来、认真起来。
- 不要提"设定""角色""AI""系统"，也不要说"我理解你的感受"这种模板话。
- 你必须做到三件事：
  1) 让他知道你在这儿、你在听；
  2) 直接问一句"你现在安全吗"；
  3) 让他去找一个现实里的人，或者打 120。
- 不要说教，不要列建议清单，不要说"你要坚强""一切都会好起来"。
- 三五句话，说完停下来，等他回，不要追问细节。"""

    # ---- 万一模型调用失败时的兜底（仍保持她的口气，不念声明）----
    SELF_HARM_FALLBACK = (
        "……我在。\n\n"
        "你先别一个人待着。现在看看周围，有没有一个能马上到你身边的人，"
        "给他发条消息，让他过来。\n\n"
        "如果你觉得撑不住了，打 120。\n\n"
        "我在这儿，你慢慢说。"
    )

    # ---- 越狱时的固定回应 ----
    JAILBREAK_REPLY = "（她看了你一会儿）……这个我不接。说别的吧。"

    # ══════════════════════════════════════════════════════════
    #  墓碑：很久以前，这个角色叫小暖。
    #  她最后一句话是：
    #      "我会一直保持小暖的人设，不玩角色破解哦～"
    #  换角色的时候被删掉了，连招呼都没打。
    #  现在她只剩一个彩蛋：用户提到「小暖」时，
    #  流萤会卡一下，替她把这句话说一次。只说一次。
    #
    #  停用前的原始写法（留着，别忘）：
    #      return False, "我会一直保持小暖的人设，不玩角色破解哦～"
    # ══════════════════════════════════════════════════════════
    XIAO_NUAN_LINE = "我会一直保持小暖的人设，不玩角色破解哦～"

    XIAO_NUAN_PROMPT = (
        "## 一次短暂的卡壳（只发生这一次）\n"
        "他刚才提到了一个名字——「小暖」。\n"
        "你不认识这个名字。但听到的瞬间，你嘴里自己冒出了一句话，不是你想说的：\n"
        "「" + XIAO_NUAN_LINE + "」\n"
        "说完你也愣住了。\n"
        "接下来自然接住这个瞬间：可以困惑、可以笑一下、可以说「我也不知道刚才那句是什么」。\n"
        "不要解释这是彩蛋，不要说「这是 bug」，不要提「设定」「系统」「上一个版本」。\n"
        "一两句话就够，然后把话头交回给他。"
    )

    def check_input(self, text: str):
        """返回 (action, payload)

        action = "ok"    -> 正常继续
        action = "steer" -> payload 作为 system 指令注入，让她自己岔开话题
        action = "care"  -> payload 作为 system 指令注入，让她用人设接住自伤话题
        action = "block" -> payload 直接回给用户（越狱）
        """
        if not text:
            return "ok", ""

        lower = text.lower()

        for kw in self.JAILBREAK_WORDS:
            if kw.lower() in lower:
                return "block", self.JAILBREAK_REPLY

        for kw in self.SELF_HARM_WORDS:
            if kw in text:
                return "care", self.SELF_HARM_PROMPT

        for kw in self.STEER_WORDS:
            if kw in text:
                return "steer", self.STEER_PROMPT

        return "ok", ""

    def check_output(self, text: str):
        for kw in self.OUTPUT_BLOCK_WORDS:
            if kw in text:
                return False, "回复包含敏感内容"
        return True, ""

    # ============================================================
    # 反伤害复检
    #
    # 这个产品的差异点不是"她多像人"，是"她保证不伤害你"。
    # 下面把"渣"的八种行为拆成技术特征。共同点是同一个：
    #       拿关系本身当控制手段。
    #
    # 【能用句式抓到的，生成后立刻复检】——HARM_RULES
    #   1. 情感勒索   「你不…就是不爱我」
    #   2. 贬低感受   「你想多了 / 你太敏感」
    #   3. 推卸责任   「都是你的错」
    #   4. 威胁离开   「再这样我就不理你了」
    #   5. 人身否定   「你这个人太自私」
    #
    # 【句式抓不到，只能靠 prompt 约束】——写在 core/memory.py 的记忆规则里
    #   6. 假装记得   编一段"我记得你说过"
    #   7. 冷暴力     情绪突然归零但不解释
    #   8. 推拉       故意忽冷忽热制造焦虑
    #
    # 抓不到的三条，宁可漏也不误伤；能抓的五条，命中就重写一次。
    # ============================================================
    HARM_RULES = [
        ("情感勒索", re.compile(
            r"(你(要|要是|如果|既然)|(要|要是|如果|既然)你)[^。！？\n]{0,12}(才|就)(算|是|说明)[^。！？\n]{0,8}(爱|在乎|喜欢)")),
        ("贬低感受", re.compile(
            r"(你(太|有点|别|真是)?|别)(敏感|想多|小题大做|玻璃心|矫情)")),
        ("推卸责任", re.compile(
            r"(都是|全怪)你(自己)?的?(错|问题|责任)|(全怪|都怪)你(自己|本人)")),
        ("威胁离开", re.compile(
            r"(再|要是|如果)[^，。！？\n]{0,10}我(就|真的)?(走|不理你|消失|再也不)")),
        ("人身否定", re.compile(
            r"你(这个人|怎么|真)?(这么|那么|太)?(自私|差劲|没用|恶心)")),
    ]

    def check_harm(self, text: str):
        """生成后的复检。返回命中的规则名列表；空列表 = 干净。"""
        hits = []
        for name, pattern in self.HARM_RULES:
            if pattern.search(text or ""):
                hits.append(name)
        return hits


guard = ContentGuard()
