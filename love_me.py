# 三、打印工具（也给别的脚本用）
# ==========================================================

def label(went, waited, poor):
    """给一种组合起个中文名字，用来打印。"""
    parts = []
    parts.append("去了漫展" if went else "没去漫展")
    parts.append("等了她" if waited else "急着推进")
    parts.append("装了穷" if poor else "没装穷")
    return " · ".join(parts)


def all_versions():
    """把八种组合全列出来，按"离现实远近"排。

    返回 [(标签, 正文), ...]，一共八条。
    """
    out = []
    # 从最接近现实的那一种开始
    order = [
        (False, False, True),    # 实际发生的
        (False, True,  True),
        (False, False, False),
        (False, True,  False),
        (True,  False, True),
        (True,  True,  True),
        (True,  False, False),
        (True,  True,  False),   # 全对
    ]
    for went, waited, poor in order:
        out.append((label(went, waited, poor),
                    love_me(went=went, waited=waited, poor=poor)))
    return out


def is_real(went=False, waited=False, poor=True):
    """这一种是不是实际发生的那一版。"""
    return (went is False) and (waited is False) and (poor is True)


